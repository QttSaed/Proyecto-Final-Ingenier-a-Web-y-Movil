const login = (email: string) => {
  cy.get('.ion-page:not(.ion-page-hidden) #email').type(email);
  cy.get('.ion-page:not(.ion-page-hidden) #password').type('123456');
  cy.get('.ion-page:not(.ion-page-hidden) .btn-login').click();
};
describe('Acceso por roles y navegación Ionic', () => {
  beforeEach(() => cy.clearLocalStorage());
  it('vuelve al checkout después de iniciar sesión y permite cerrar sesión', () => {
    cy.visit('/checkout');
    cy.location('pathname').should('eq', '/login');
    login('cliente@tcgstore.com');
    cy.location('pathname').should('eq', '/checkout');
    cy.contains('h1', 'Finalizar Compra').should('be.visible');
    cy.get('.ion-page:not(.ion-page-hidden) .header-icons button').filter(':visible').first().click();
    cy.location('pathname').should('eq', '/perfil');
    cy.get('.ion-page:not(.ion-page-hidden) .logout-btn').click();
    cy.location('pathname').should('eq', '/login');
    cy.get('.ion-page:not(.ion-page-hidden) .login-card').should('be.visible');
    login('cliente@tcgstore.com');
    cy.location('pathname').should('eq', '/perfil');
    cy.get('.ion-page:not(.ion-page-hidden) .profile-title').should('be.visible');
  });
  it('envía al admin al dashboard, permite recorrer la tienda y bloquea las compras', () => {
    cy.viewport(1440, 900);
    cy.visit('/login');
    login('admin@tcgstore.com');
    cy.location('pathname').should('eq', '/admin');
    cy.contains('button', 'Volver al inicio').click();
    cy.location('pathname').should('eq', '/home');
    cy.get('.ion-page:not(.ion-page-hidden) .banner-large img').should('be.visible');
    cy.get('.admin-content').should('not.be.visible');
    cy.get('.ion-page:not(.ion-page-hidden) nav.header-links').contains('Eventos').click();
    cy.location('pathname').should('eq', '/catalog/eventos');
    cy.get('.admin-content').should('not.be.visible');
    cy.visit('/admin/inventario');
    cy.contains('Inventario de Productos').should('be.visible');
    cy.visit('/admin/ordenes');
    cy.get('.status-select').first().find('option').should('have.length', 4);
    cy.visit('/cart');
    cy.location('pathname').should('eq', '/admin');
    cy.visit('/checkout');
    cy.location('pathname').should('eq', '/admin');
    cy.visit('/product/pokemon-0');
    cy.get('.btn-add-cart').should('be.disabled');
  });
  it('muestra 404 y permite volver al inicio en móvil', () => {
    cy.viewport(390, 844);
    cy.visit('/ruta-inexistente');
    cy.contains('Página no encontrada').should('be.visible');
    cy.contains('Volver al inicio').click();
    cy.location('pathname').should('eq', '/home');
    cy.get('.ion-page:not(.ion-page-hidden) .banner-large img').should('be.visible');
  });
  it('registra clientes y bloquea su acceso a administración', () => {
    const email = `cliente-${Date.now()}@example.cl`;
    cy.visit('/register');
    cy.get('#nombre').type('Nueva');
    cy.get('#apellido').type('Cliente');
    cy.get('#email').type(email);
    cy.get('#password').type('Segura123');
    cy.get('#confirmPassword').type('Diferente123');
    cy.get('#terms').check();
    cy.get('.btn-register').click();
    cy.contains('Las contraseñas deben coincidir.').should('be.visible');
    cy.get('#confirmPassword').clear().type('Segura123');
    cy.get('.btn-register').click();
    cy.location('pathname').should('eq', '/login');
    cy.contains('Cuenta creada.').should('be.visible');
    cy.get('#email').type(email);
    cy.get('#password').type('Segura123');
    cy.get('.btn-login').click();
    cy.location('pathname').should('eq', '/perfil');
    cy.visit('/admin');
    cy.location('pathname').should('eq', '/home');
  });
  it('combina los ocho filtros reales y amplía una imagen', () => {
    cy.visit('/catalog/todos');
    cy.get('.btn-filter-trigger').click();
    cy.get('.filter-dropdown-menu select[id^="filter-"]').should('have.length', 8);
    cy.get('#filter-category').select('Accesorios');
    cy.get('#filter-game').select('Multijuego');
    cy.get('#filter-edition').select('Sin especificar');
    cy.get('#filter-rarity').select('Rare');
    cy.get('#filter-color').select('Azul');
    cy.get('#filter-cost').select('23000');
    cy.get('#filter-cardType').select('Accesorio');
    cy.get('#filter-condition').select('Near Mint');
    cy.get('.btn-apply-filters').click();
    cy.get('.catalog-grid .product-card').should('have.length', 1);
    cy.get('.catalog-grid').contains('.product-title', '160 Top Deck Azul').should('be.visible').click();
    cy.get('.badge-condition').should('have.text', 'Near Mint');
    cy.get('.badge-rarity').should('have.text', 'Rare');
    cy.get('.detail-image').click();
    cy.get('ion-modal img').should('be.visible');
    cy.get('ion-modal button').contains('Cerrar vista ampliada').click();
    cy.get('.btn-add-cart').click();
    cy.get('.cart-notice').should('be.visible');
  });
});
