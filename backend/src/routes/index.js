const { Router } = require('express');
const auth = require('../controllers/auth');
const products = require('../controllers/products');
const orders = require('../controllers/orders');
const admin = require('../controllers/admin');
const categories = require('../controllers/categories');
const { authenticateJWT, authorizeRoles } = require('../middlewares/auth');
const { body } = require('../middlewares/validate');
const router = Router();
const optionalAuth = (req, res, next) => req.headers.authorization ? authenticateJWT(req, res, next) : next();
router.get('/admin/stats', authenticateJWT, authorizeRoles('admin'), admin.stats);
router.get('/health', (req, res) => res.json({ status: 'ok' }));
router.post('/auth/register', body, auth.register);
router.post('/auth/verify-email', body, auth.verifyEmail);
router.get('/auth/verify-email', auth.verifyEmail);
router.post('/auth/resend-verification', body, auth.resendVerification);
router.post('/auth/login', body, auth.login);
router.get('/auth/me', authenticateJWT, auth.me);
router.put('/auth/me', authenticateJWT, body, auth.updateMe);
router.get('/categories', categories.list);
router.get('/products', optionalAuth, products.list);
router.get('/products/:id', optionalAuth, products.detail);
router.post('/products', authenticateJWT, authorizeRoles('admin'), body, products.create);
router.put('/products/:id', authenticateJWT, authorizeRoles('admin'), body, products.update);
router.delete('/products/:id', authenticateJWT, authorizeRoles('admin'), products.remove);
router.post('/orders', authenticateJWT, authorizeRoles('client'), body, orders.create);
router.get('/orders', authenticateJWT, orders.list);
router.get('/orders/:id', authenticateJWT, orders.detail);
router.patch('/orders/:id/status', authenticateJWT, authorizeRoles('admin'), body, orders.status);
router.put('/orders/:id/status', authenticateJWT, authorizeRoles('admin'), body, orders.status);
module.exports = router;
